// Gate for the text that goes into history: commit messages, PR title, PR body
// and PR target. No dependencies: runs directly on Node 22.18+, which strips
// TypeScript types without a build step.
//
// Usage:
//   node tools/check-commits.ts <base>
//       Checks the commits in <base>..HEAD (for example origin/main). If <base>
//       does not exist yet (new repository, before the first push), checks all.
//   node tools/check-commits.ts --message <file>
//       Checks a single message. This is the mode for a commit-msg hook.
//
// Optional environment variables (CI fills them in):
//   PR_TITLE          PR title. With squash merge it becomes the commit subject on main.
//   PR_BODY           PR body. With squash merge it becomes the commit body on main,
//                     so it goes through the same text rules.
//   PR_BASE           PR target branch. Must be main.
//   FORBIDDEN_TERMS   list (one per line or comma separated) of terms that must
//                     never appear: names of people, companies, customers. In CI it
//                     comes from a secret, so the list itself is never public.
//   FORBIDDEN_TERMS_FILE  local file with the same list. Default:
//                     ~/.config/quality-gate/forbidden-terms.txt
//
// Rules:
// 1. Subject follows Conventional Commits: type(optional scope): description
// 2. Subject has at most 72 characters and no trailing period
// 3. No co-author or "generated by" lines
// 4. No e-mail address and no forbidden term, ignoring case and accents
// 5. PRs always target main

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

export const TYPES = ['feat', 'fix', 'docs', 'style', 'refactor', 'perf', 'test', 'build', 'ci', 'chore', 'revert'];
export const MAX_SUBJECT = 72;
export const MAIN_BRANCH = 'main';

const SUBJECT = new RegExp(`^(${TYPES.join('|')})(\\([a-z0-9-]+\\))?!?: \\S.*$`);
// \u{1F916} is the robot emoji some tools add to their signature.
const THIRD_PARTY_AUTHORSHIP = /^\s*(co-authored-by:|signed-off-by:|generated (with|by)\b)|\u{1F916}/imu;
const EMAIL = /[\p{L}\p{N}._%+-]+@[\p{L}\p{N}-]+(\.[\p{L}\p{N}-]+)*\.\p{L}{2,}/u;

// Scissors line git puts in the editor with "commit -v": below it is the diff.
const SCISSORS = /^# -+ >8 -+$/m;

/** Lowercase, no accents: "José" and "jose" are the same term. */
export function normalize(text: string): string {
  return text.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase();
}

/** Reads the term list: one per line or comma separated; # starts a comment. */
export function parseTerms(text: string): string[] {
  return text
    .split(/[\n,]/)
    .map((line) => (line.split('#', 1)[0] ?? '').trim())
    .filter(Boolean);
}

function containsTerm(normalizedText: string, term: string): boolean {
  const escaped = normalize(term).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(^|[^\\p{L}\\p{N}])${escaped}($|[^\\p{L}\\p{N}])`, 'u').test(normalizedText);
}

/** Rules for any text that goes into history. */
export function textProblems(text: string, terms: readonly string[] = []): string[] {
  const problems: string[] = [];
  if (THIRD_PARTY_AUTHORSHIP.test(text)) problems.push('has a co-author or "generated by" line');
  if (EMAIL.test(text)) problems.push('has an e-mail address');
  const normalized = normalize(text);
  // The message gives only the term number: the CI log is public and must not repeat the term.
  terms.forEach((term, index) => {
    if (containsTerm(normalized, term)) problems.push(`has forbidden term #${index + 1} from the list`);
  });
  return problems;
}

/** Problems with a commit subject (empty list when it is fine). */
export function subjectProblems(subject: string): string[] {
  const problems: string[] = [];
  if (!SUBJECT.test(subject)) {
    problems.push(`not in the "type(scope): description" format (types: ${TYPES.join(', ')})`);
  }
  if (subject.length > MAX_SUBJECT) {
    problems.push(`has ${subject.length} characters (max ${MAX_SUBJECT})`);
  }
  if (subject.endsWith('.')) problems.push('ends with a period');
  return problems;
}

/** Problems with the whole message (subject + body). */
export function messageProblems(message: string, terms: readonly string[] = []): string[] {
  const subject = message.split('\n', 1)[0] ?? '';
  return [...subjectProblems(subject.trim()), ...textProblems(message, terms)];
}

/** Message as git stores it: without the "commit -v" diff and without comment lines. */
export function cleanEditorMessage(raw: string): string {
  const withoutDiff = raw.split(SCISSORS, 1)[0] ?? '';
  return withoutDiff
    .split('\n')
    .filter((line) => !line.startsWith('#'))
    .join('\n')
    .trim();
}

/** Problem with the PR target, or null when it targets main. */
export function baseProblem(base: string): string | null {
  return base === MAIN_BRANCH
    ? null
    : `the PR targets "${base}"; every PR goes straight to ${MAIN_BRANCH} (stacked PRs bypass branch protection)`;
}

interface Item {
  label: string;
  problems: string[];
}

function git(args: string[]): string {
  return execFileSync('git', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
}

function existsInGit(ref: string): boolean {
  try {
    git(['rev-parse', '--verify', '--quiet', `${ref}^{commit}`]);
    return true;
  } catch {
    return false;
  }
}

function commitsSince(base: string, terms: readonly string[]): Item[] {
  if (!existsInGit('HEAD')) return []; // repository with no commits yet
  const range = existsInGit(base) ? `${base}..HEAD` : 'HEAD';
  // %x00 separates commits; %x01 separates hash and message.
  const output = git(['log', '--no-merges', '--format=%h%x01%B%x00', range]);
  return output
    .split('\0')
    .map((block) => block.trim())
    .filter(Boolean)
    .map((block) => {
      const [hash = '', message = ''] = block.split('\x01');
      return { label: `commit ${hash}`, problems: messageProblems(message.trim(), terms) };
    });
}

function configuredTerms(): string[] {
  const fromEnv = parseTerms(process.env['FORBIDDEN_TERMS'] ?? '');
  const file =
    process.env['FORBIDDEN_TERMS_FILE'] ?? join(homedir(), '.config', 'quality-gate', 'forbidden-terms.txt');
  const fromFile = existsSync(file) ? parseTerms(readFileSync(file, 'utf8')) : [];
  const terms = [...fromEnv, ...fromFile];
  // On GitHub Actions, mask every term in the log in case a step prints it.
  if (process.env['GITHUB_ACTIONS'] === 'true') for (const term of terms) console.log(`::add-mask::${term}`);
  return terms;
}

function prItems(terms: readonly string[]): Item[] {
  const items: Item[] = [];
  const title = process.env['PR_TITLE'];
  if (title) {
    items.push({ label: 'PR title', problems: [...subjectProblems(title.trim()), ...textProblems(title, terms)] });
  }
  const body = process.env['PR_BODY'];
  if (body) items.push({ label: 'PR body', problems: textProblems(body, terms) });
  const base = process.env['PR_BASE'];
  const problem = base ? baseProblem(base) : null;
  if (problem) items.push({ label: 'PR target', problems: [problem] });
  return items;
}

function report(items: Item[]): number {
  const failed = items.filter((item) => item.problems.length > 0);
  for (const item of failed) {
    console.error(`FAILED  ${item.label}`);
    for (const problem of item.problems) console.error(`        - ${problem}`);
  }
  console.log(`${items.length} item(s) checked, ${failed.length} failed.`);
  return failed.length > 0 ? 1 : 0;
}

function main(args: string[]): number {
  const terms = configuredTerms();
  if (args[0] === '--message' && args[1]) {
    const message = cleanEditorMessage(readFileSync(args[1], 'utf8'));
    return report([{ label: 'commit message', problems: messageProblems(message, terms) }]);
  }
  const base = args[0];
  if (!base || base.startsWith('--')) {
    console.error('Usage: node tools/check-commits.ts <base> | --message <file>');
    return 2;
  }
  return report([...commitsSince(base, terms), ...prItems(terms)]);
}

// Run from the command line (not imported by a test).
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  process.exitCode = main(process.argv.slice(2));
}
